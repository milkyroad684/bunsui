def stable_seed(tag):
    """Process-stable seed for scramble. Unlike the builtin hash(), crc32 is
    not affected by PYTHONHASHSEED, so build artifacts stay deterministic."""
    return zlib.crc32(tag.encode("utf-8")) & 0xFFFF

